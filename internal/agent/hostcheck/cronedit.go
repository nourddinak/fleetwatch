// Changing cron jobs from the dashboard. Pausing comments a line out (with a mark, so
// it shows as paused and can come back); timers are disabled and enabled. Adding or
// changing a command runs new code on this server, so it follows the agent's
// allowCustomCommands switch, like custom app commands.

var (
	scheduleRe = regexp.MustCompile(`^([0-9*,/\-a-zA-Z?]+ ){4}[0-9*,/\-a-zA-Z?]+$`)
	userRe     = regexp.MustCompile(`^[a-z_][a-z0-9_.-]{0,31}$`)
)

const customOff = "adding or changing commands is turned off on this server (allowCustomCommands=false in /etc/ops-agent/config.json)"

// installCrontab replaces a user's crontab (tests replace it).
var installCrontab = func(ctx context.Context, userName, content string) error {
	tmp, err := os.CreateTemp("", "fw-crontab-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return err
	}
	tmp.Close()
	_, err = sysexec.Run(ctx, sysexec.Opts{Timeout: 15 * time.Second}, "crontab", "-u", userName, tmp.Name())
	return err
}

// ChangeCron applies one change and says how it went.
func ChangeCron(ctx context.Context, c proto.CronChange, allowCustom bool) proto.CronResult {
	res := proto.CronResult{RunID: c.RunID, Op: c.Op, JobID: c.JobID}
	fail := func(err error) proto.CronResult {
		res.Error, res.ExitCode = err.Error(), -1
		return res
	}
	if (c.Op == "add" || c.Op == "update") && !allowCustom {
		return fail(errors.New(customOff))
	}
	if c.Op == "add" || c.Op == "update" {
		if err := checkJob(c.Schedule, c.Command); err != nil {
			return fail(err)
		}
	}
	if c.Op == "add" {
		if !userRe.MatchString(c.User) {
			return fail(errors.New("not a valid user name"))
		}
		if _, err := user.Lookup(c.User); err != nil {
			return fail(errors.New("there is no user " + c.User + " on this server"))
		}
		path := p("var", "spool", "cron", "crontabs", c.User)
		if _, err := os.Stat(p("var", "spool", "cron", "crontabs")); err != nil {
			path = p("var", "spool", "cron", c.User) // Red Hat style
		}
		old, _ := os.ReadFile(path)
		content := strings.TrimRight(string(old), "\n")
		if content != "" {
			content += "\n"
		}
		if err := installCrontab(ctx, c.User, withoutHeader(content+c.Schedule+" "+c.Command+"\n")); err != nil {
			return fail(err)
		}
		res.JobID = jobID(onHost(path), c.User, c.Schedule, c.Command)
		return res
	}
	if unit, ok := strings.CutPrefix(c.JobID, "timer:"); ok {
		return changeTimer(ctx, res, c, unit)
	}
	loc, err := findCron(c.JobID)
	if err != nil {
		return fail(err)
	}
	if c.Op == "run" {
		return runCron(ctx, res, loc.user, loc.cmd)
	}
	lines := loc.lines
	switch c.Op {
	case "delete":
		lines = append(lines[:loc.index:loc.index], lines[loc.index+1:]...)
	case "pause", "resume", "update":
		line := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(lines[loc.index]), pausedMark))
		if c.Op == "update" {
			line = c.Schedule + " " + c.Command
			if loc.system {
				line = c.Schedule + " " + loc.user + " " + c.Command
			}
			if loc.paused {
				line = pausedMark + line
			}
		} else if c.Op == "pause" {
			line = pausedMark + line
		}
		lines[loc.index] = line
		if c.Op == "update" {
			res.JobID = jobID(onHost(loc.path), loc.user, c.Schedule, c.Command)
		}
	default:
		return fail(errors.New("unknown change " + c.Op))
	}
	if err := loc.write(ctx, strings.Join(lines, "\n")); err != nil {
		return fail(err)
	}
	return res
}

// withoutHeader drops the "DO NOT EDIT THIS FILE" lines crontab writes at the top of
// each user's file: crontab adds them again on every install.
func withoutHeader(content string) string {
	var keep []string
	for _, l := range strings.Split(content, "\n") {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "# DO NOT EDIT THIS FILE") || strings.HasPrefix(t, "# (Cron version") || (strings.HasPrefix(t, "# (") && strings.Contains(t, " installed on ")) {
			continue
		}
		keep = append(keep, l)
	}
	return strings.Join(keep, "\n")
}

func checkJob(sched, cmd string) error {
	switch {
	case !scheduleRe.MatchString(sched) && !shortcuts[sched]:
		return errors.New("the schedule must be five fields like */5 * * * *, or @hourly, @daily, @weekly, @monthly")
	case strings.TrimSpace(cmd) == "" || len(cmd) > 2000 || strings.ContainsAny(cmd, "\n\r"):
		return errors.New("the command must be one line (up to 2000 characters)")
	case strings.Contains(cmd, "%") && !strings.Contains(cmd, `\%`):
		return errors.New(`cron reads % as a new line: write \% for a percent sign`)
	}
	return nil
}

// cronLoc is where a job's line is.
type cronLoc struct {
	path, user, cmd string
	system, paused  bool // system: the user is named on the line (/etc/crontab, /etc/cron.d)
	lines           []string
	index           int
}

func (l cronLoc) write(ctx context.Context, content string) error {
	content = strings.TrimRight(content, "\n") + "\n"
	if !l.system {
		return installCrontab(ctx, l.user, withoutHeader(content))
	}
	st, err := os.Stat(l.path)
	if err != nil {
		return err
	}
	tmp := filepath.Join(filepath.Dir(l.path), "."+filepath.Base(l.path)+".fleetwatch") // cron skips names with dots
	if err := os.WriteFile(tmp, []byte(content), st.Mode().Perm()); err != nil {
		return err
	}
	return os.Rename(tmp, l.path)
}

// findCron finds the line of a crontab job by its ID.
func findCron(id string) (cronLoc, error) {
	var files []cronLoc
	files = append(files, cronLoc{path: p("etc", "crontab"), system: true})
	if list, _ := filepath.Glob(p("etc", "cron.d", "*")); list != nil {
		for _, f := range list {
			files = append(files, cronLoc{path: f, system: true})
		}
	}
	for _, dir := range []string{p("var", "spool", "cron", "crontabs"), p("var", "spool", "cron")} {
		entries, _ := os.ReadDir(dir)
		for _, e := range entries {
			if !e.IsDir() {
				files = append(files, cronLoc{path: filepath.Join(dir, e.Name()), user: e.Name()})
			}
		}
	}
	for _, f := range files {
		b, err := os.ReadFile(f.path)
		if err != nil {
			continue
		}
		f.lines = strings.Split(strings.TrimRight(string(b), "\n"), "\n")
		owner := f.user
		for i, line := range f.lines {
			sched, u, cmd, paused, ok := cronLine(line, owner)
			if ok && jobID(onHost(f.path), u, sched, cmd) == id {
				f.index, f.user, f.cmd, f.paused = i, u, cmd, paused
				return f, nil
			}
		}
	}
	return cronLoc{}, errors.New("that job is not on the server any more (it may have just changed)")
}

// runCron runs a job's command now, as its user and like cron does (/bin/sh, in the
// user's home), for up to 10 minutes.
func runCron(ctx context.Context, res proto.CronResult, userName, cmd string) proto.CronResult {
	u, err := user.Lookup(userName)
	if err != nil {
		res.Error, res.ExitCode = "there is no user "+userName+" on this server", -1
		return res
	}
	uid, _ := strconv.Atoi(u.Uid)
	gid, _ := strconv.Atoi(u.Gid)
	o := sysexec.Opts{Dir: u.HomeDir, UID: uid, GID: gid, AsUser: uid != 0, Timeout: 10 * time.Minute, MaxOut: 32 << 10,
		Env: []string{"PATH=/usr/local/bin:/usr/bin:/bin", "HOME=" + u.HomeDir, "USER=" + userName, "LOGNAME=" + userName, "SHELL=/bin/sh", "LANG=C.UTF-8"}}
	if _, err := os.Stat(u.HomeDir); err != nil {
		o.Dir = "/"
	}
	out, err := sysexec.Run(ctx, o, "/bin/sh", "-c", "exec 2>&1; "+cmd)
	res.Output = string(out)
	if err != nil {
		res.Error, res.ExitCode = err.Error(), 1
	}
	return res
}

// changeTimer runs, pauses or resumes a systemd timer (its schedule lives in its unit file).
func changeTimer(ctx context.Context, res proto.CronResult, c proto.CronChange, unit string) proto.CronResult {
	if !strings.HasSuffix(unit, ".timer") || strings.ContainsAny(unit, "/ ") {
		res.Error, res.ExitCode = "not a timer", -1
		return res
	}
	var args []string
	switch c.Op {
	case "pause":
		args = []string{"disable", "--now", unit}
	case "resume":
		args = []string{"enable", "--now", unit}
	case "run":
		svc := show(ctx, unit, "Unit")["Unit"]
		if svc == "" {
			svc = strings.TrimSuffix(unit, ".timer") + ".service"
		}
		_, err := sysexec.Run(ctx, sysexec.Opts{Timeout: 10 * time.Minute}, "systemctl", "start", svc)
		out, _ := sysexec.Run(ctx, sysexec.Opts{Timeout: 15 * time.Second}, "journalctl", "-u", svc, "-n", "40", "--no-pager", "-o", "cat")
		res.Output = string(out)
		if err != nil {
			res.Error, res.ExitCode = err.Error(), 1
		}
		return res
	default:
		res.Error, res.ExitCode = "a systemd timer's schedule and command are in its unit files: change them there", -1
		return res
	}
	if _, err := sysexec.Run(ctx, sysexec.Opts{Timeout: 30 * time.Second}, "systemctl", args...); err != nil {
		res.Error, res.ExitCode = err.Error(), -1
	}
	return res
}
