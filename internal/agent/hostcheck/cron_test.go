func TestCrontab(t *testing.T) {
	Root = t.TempDir()
	defer func() { Root = "/" }()
	os.MkdirAll(p("var", "spool", "cron", "crontabs"), 0o755)
	os.MkdirAll(p("etc"), 0o755)
	os.WriteFile(p("var", "spool", "cron", "crontabs", "deploy"), []byte(`# m h dom mon dow command
MAILTO=""
*/5 * * * * cd /srv/app && php artisan schedule:run >> /dev/null 2>&1
@daily   /opt/backup.sh --all
@reboot /opt/start.sh
`), 0o600)
	os.WriteFile(p("etc", "crontab"), []byte(`SHELL=/bin/sh
17 *	* * *	root	cd / && run-parts --report /etc/cron.hourly
0 4 * * 1-5 www-data /usr/bin/php /var/www/cleanup.php
`), 0o644)
	jobs := crontab(p("var", "spool", "cron", "crontabs", "deploy"), "crontab", "deploy")
	if len(jobs) != 2 || jobs[0].Schedule != "*/5 * * * *" || jobs[0].Command != "cd /srv/app && php artisan schedule:run >> /dev/null 2>&1" ||
		jobs[1].Schedule != "@daily" || jobs[1].User != "deploy" || jobs[0].File != "/var/spool/cron/crontabs/deploy" {
		t.Fatalf("%+v", jobs)
	}
	sys := crontab(p("etc", "crontab"), "cron.d", "")
	if len(sys) != 1 || sys[0].User != "www-data" || sys[0].Command != "/usr/bin/php /var/www/cleanup.php" {
		t.Fatalf("%+v", sys)
	}
	if again := crontab(p("var", "spool", "cron", "crontabs", "deploy"), "crontab", "deploy"); again[0].ID != jobs[0].ID {
		t.Fatal("IDs change between reads")
	}
	r := runLog{"deploy\x00cd /srv/app && php artisan schedule:run >> /dev/null 2>&1": 5, "root\x00/opt/a-very-long-command-that-cron-shortened-in-its-log": 9}
	if r.last("deploy", jobs[0].Command) != 5 || r.last("root", "/opt/a-very-long-command-that-cron-shortened-in-its-log --and more") != 9 {
		t.Fatal("last runs")
	}
	os.Symlink("/usr/share/zoneinfo/Europe/Berlin", filepath.Join(Root, "etc", "localtime"))
	if tz := timeZone(); tz != "Europe/Berlin" && tz != "UTC" { // symlinks may not be allowed (Windows)
		t.Fatal(tz)
	}
}

func TestChangeCron(t *testing.T) {
	Root = t.TempDir()
	defer func() { Root = "/" }()
	dir := p("var", "spool", "cron", "crontabs")
	os.MkdirAll(dir, 0o755)
	os.MkdirAll(p("etc", "cron.d"), 0o755)
	installCrontab = func(_ context.Context, u, content string) error {
		return os.WriteFile(filepath.Join(dir, u), []byte(content), 0o600)
	}
	os.WriteFile(filepath.Join(dir, "root"), []byte("# DO NOT EDIT THIS FILE - edit the master and reinstall.\n# (/tmp/x installed on Tue Oct 20 21:40:20 2026)\n"+
		"# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n# keep me\n*/5 * * * * /opt/a.sh\n"), 0o600)
	os.WriteFile(p("etc", "cron.d", "app"), []byte("0 4 * * * www-data /opt/clean.sh\n"), 0o644)
	ctx := context.Background()
	jobs := func() []proto.CronJob {
		return append(crontab(filepath.Join(dir, "root"), "crontab", "root"), crontab(p("etc", "cron.d", "app"), "cron.d", "")...)
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "update", JobID: jobs()[0].ID, Schedule: "0 * * * *", Command: "/opt/b.sh"}, false); r.Error == "" {
		t.Fatal("changed a command with custom commands off")
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "update", JobID: jobs()[0].ID, Schedule: "0 * * * * *", Command: "/opt/b.sh"}, true); r.Error == "" {
		t.Fatal("six-field schedule accepted")
	}
	r := ChangeCron(ctx, proto.CronChange{Op: "update", JobID: jobs()[0].ID, Schedule: "0 * * * *", Command: "/opt/b.sh"}, true)
	if r.Error != "" || jobs()[0].Command != "/opt/b.sh" || r.JobID != jobs()[0].ID {
		t.Fatal(r, jobs())
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "pause", JobID: jobs()[1].ID}, false); r.Error != "" || !jobs()[1].Paused {
		t.Fatal("pause", r, jobs())
	}
	b, _ := os.ReadFile(p("etc", "cron.d", "app"))
	if string(b) != pausedMark+"0 4 * * * www-data /opt/clean.sh\n" {
		t.Fatalf("%q", b)
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "resume", JobID: jobs()[1].ID}, false); r.Error != "" || jobs()[1].Paused {
		t.Fatal("resume", r)
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "delete", JobID: jobs()[0].ID}, false); r.Error != "" {
		t.Fatal(r)
	}
	b, _ = os.ReadFile(filepath.Join(dir, "root"))
	if string(b) != "# keep me\n" || len(jobs()) != 1 {
		t.Fatalf("%q", b)
	}
	if r := ChangeCron(ctx, proto.CronChange{Op: "delete", JobID: "nope"}, false); r.Error == "" {
		t.Fatal("deleted a job that is not there")
	}
}
